/** A symbol pin as placed: anchor plus whether KiCad hides it (stacked under a visible pin). */
export interface UnitPin extends PinAnchor {
  hidden: boolean;
  type: string;
  name: string;
}

export interface SymbolUnit {
  unit: number;
  /** Pin number → anchor, including pins common to all units. */
  pins: Map<string, UnitPin>;
  box: { minX: number; maxX: number; minY: number; maxY: number };
}

/** A symbol ready to place: KiCad's own or a generated one. */
export interface SchSymbol {
  /** `Device:R`, `partstyle:L7805CV`. */
  libId: string;
  /** Definition named after libId, for a schematic's lib_symbols. */
  def: SExpr[];
  units: SymbolUnit[];
  /** Set for symbols generated by partstyle (they go into partstyle.kicad_sym). */
  generated?: GeneratedSymbol;
  /** The library's own Reference/Value placement (symbol coords, y up), for KiCad symbols. */
  fields?: { reference?: LibField; value?: LibField };
}

export interface LibField {
  x: number;
  y: number;
  angle: number;
  justify: string[];
  hidden: boolean;
}

/** A property's position and justification as the library author placed it. */
function fieldOf(def: SExpr[], name: string): LibField | undefined {
  const prop = children(def, "property").find((p) => p[1] === name);
  if (!prop) return undefined;
  const [x = 0, y = 0, angle = 0] = numbers(child(prop, "at") ?? []);
  const effects = child(prop, "effects");
  const justify =
    (effects &&
      child(effects, "justify")
        ?.slice(1)
        .flatMap((j) => atomText(j) ?? [])) ??
    [];
  const hidden =
    child(prop, "hide") !== undefined ||
    (effects !== undefined && child(effects, "hide") !== undefined);
  return { x, y, angle, justify, hidden };
}

/** Key shared by every part that uses the same symbol: `lib:L7805CV`, `generic:diode:schottky`. */
export function symbolKey(part: FlatPart): string {
  if (part.spec.kind === "lib") return `lib:${part.spec.id}`;
  const { fn, args } = part.spec;
  const kind =
    fn === "diode"
      ? (args[0] ?? "").toLowerCase()
      : fn === "fp"
        ? genericSymbolId(fn, args)
        : parseGenericSpec(fn, args)?.polarized
          ? "polarized"
          : "";
  return `generic:${fn}${kind ? `:${kind}` : ""}`;
}

/** KiCad's Device-library symbol for a generic part. */
export function genericSymbolId(fn: string, args: string[]): string | undefined {
  switch (fn) {
    case "res":
      return "Device:R";
    case "cap":
      return parseGenericSpec(fn, args)?.polarized ? "Device:C_Polarized" : "Device:C";
    case "ind":
      return "Device:L";
    case "led":
      return "Device:LED";
    case "diode": {
      const kind = parseGenericSpec(fn, args)?.value;
      if (kind === "schottky") return "Device:D_Schottky";
      if (kind === "zener") return "Device:D_Zener";
      if (kind === "tvs") return "Device:D_TVS";
      return "Device:D";
    }
    case "fp": {
      const count = genericPins(fn, args).length;
      const bridged = /Bridged/.test(args[0] ?? "");
      if (count === 2) return `Jumper:SolderJumper_2_${bridged ? "Bridged" : "Open"}`;
      if (count === 3) return `Jumper:SolderJumper_3_${bridged ? "Bridged12" : "Open"}`;
      return "Connector:TestPoint";
    }
    default:
      return undefined;
  }
}

/**
 * The library symbol with derived symbols (`extends`) resolved into one self-contained
 * definition, as KiCad embeds them in schematics: the parent's graphics and pins under the
 * child's name, with the child's properties taking precedence.
 */
export function flattenSymbol(lib: SymbolLib, name: string, depth = 0): SExpr[] | undefined {
  const def = lib.get(name);
  if (!def || depth > 8) return undefined;
  const parentName = value(def, "extends");
  if (parentName === undefined) return def;
  const parent = flattenSymbol(lib, parentName, depth + 1);
  if (!parent) return undefined;

  const own = new Map(children(def, "property").map((p) => [p[1] as string, p]));
  const out: SExpr[] = ["symbol", name];
  let insertedOwn = false;
  for (const x of parent.slice(2)) {
    if (Array.isArray(x) && x[0] === "property") {
      const key = x[1] as string;
      out.push(own.get(key) ?? x);
      own.delete(key);
      continue;
    }
    if (Array.isArray(x) && x[0] === "symbol") {
      if (!insertedOwn) {
        out.push(...own.values()); // child-only properties (ki_keywords and the like)
        insertedOwn = true;
      }
      out.push(["symbol", `${name}${(x[1] as string).slice(parentName.length)}`, ...x.slice(2)]);
      continue;
    }
    out.push(x);
  }
  return out;
}

const atomText = (x: SExpr | undefined): string | undefined =>
  typeof x === "object" && !Array.isArray(x) ? x.sym : undefined;

function numbers(list: SExpr[]): number[] {
  return list.filter((x): x is number => typeof x === "number");
}

/** Placeable units of a (flattened) KiCad symbol definition named `name`. */
export function unitsOf(def: SExpr[]): SymbolUnit[] {
  const name = def[1] as string;
  const subs = children(def, "symbol").map((s) => {
    const m = /_(\d+)_(\d+)$/.exec((s[1] as string).slice(name.length));
    return { s, unit: Number(m?.[1] ?? 1), style: Number(m?.[2] ?? 1) };
  });
  const usable = subs.filter((x) => x.style <= 1);
  const unitNumbers = [...new Set(usable.map((x) => x.unit).filter((u) => u > 0))];
  if (unitNumbers.length === 0) unitNumbers.push(1);

  return unitNumbers
    .sort((a, b) => a - b)
    .map((unit) => {
      const parts = usable.filter((x) => x.unit === unit || x.unit === 0).map((x) => x.s);
      const pins = new Map<string, UnitPin>();
      const xs: number[] = [];
      const ys: number[] = [];
      const visit = (node: SExpr[]) => {
        for (const c of node) {
          if (!Array.isArray(c)) continue;
          if (
            c[0] === "xy" ||
            c[0] === "start" ||
            c[0] === "end" ||
            c[0] === "at" ||
            c[0] === "mid"
          ) {
            const [x, y] = numbers(c);
            if (x !== undefined && y !== undefined) {
              xs.push(x);
              ys.push(y);
            }
          } else if (c[0] !== "property" && c[0] !== "effects") {
            visit(c);
          }
        }
      };
      for (const p of parts) {
        for (const pin of children(p, "pin")) {
          const [x = 0, y = 0, angle = 0] = numbers(child(pin, "at") ?? []);
          const type = pin[1];
          pins.set(value(pin, "number") ?? "", {
            x,
            y,
            outward: (angle + 180) % 360,
            // `(hide yes)` in current files, a bare `hide` atom in older ones.
            hidden: child(pin, "hide") !== undefined || pin.some((t) => atomText(t) === "hide"),
            type: atomText(type) ?? String(type),
            name: value(pin, "name") ?? "",
          });
        }
        visit(p);
      }
      const box = {
        minX: Math.min(0, ...xs),
        maxX: Math.max(0, ...xs),
        minY: Math.min(0, ...ys),
        maxY: Math.max(0, ...ys),
      };
      return { unit, pins, box };
    });
}

/** A library symbol renamed to its lib_id, ready to place. */
export function kicadSymbol(libId: string, flattened: SExpr[]): SchSymbol {
  const reference = fieldOf(flattened, "Reference");
  const value = fieldOf(flattened, "Value");
  return {
    libId,
    def: ["symbol", libId, ...flattened.slice(2)],
    units: unitsOf(flattened),
    fields: { ...(reference && { reference }), ...(value && { value }) },
  };
}

export function generatedSymbol(g: GeneratedSymbol): SchSymbol {
  return {
    libId: `${LIB}:${g.name}`,
    def: qualified(g),
    units: [
      {
        unit: 1,
        pins: new Map(
          [...g.pins].map(([n, a]) => [n, { ...a, hidden: false, type: "", name: "" }]),
        ),
        box: g.box,
      },
    ],
    generated: g,
  };
}

/** Replaces the pin numbers in a symbol definition. */
function renumbered(node: SExpr[], numbers: Map<string, string>): SExpr[] {
  if (node[0] === "number" && typeof node[1] === "string") {
    return ["number", numbers.get(node[1]) ?? node[1], ...node.slice(2)];
  }
  return node.map((x) => (Array.isArray(x) ? renumbered(x, numbers) : x));
}

/**
 * A copy of a KiCad symbol whose pin numbers follow the part's pads, when the two pair up one to
 * one by pin name but not by number. Generic symbols number pins by role (`B C E` on
 * `Device:Q_NPN`, while a record's are pads) and pinout-specific ones may not suit the part
 * (`Q_NMOS_GSD` on a part whose pin 1 is S). It is a project symbol, as KiCad would flag an edited
 * copy of its own. Undefined when the names don't pair up, or the numbers already agree.
 */
export function adaptedSymbol(sym: SchSymbol, part: FlatPart): SchSymbol | undefined {
  if (part.spec.kind !== "lib") return undefined;
  const padOf = new Map(part.pins.map((p) => [p.name, p.number]));
  const names = new Map<string, string>();
  for (const u of sym.units) for (const [n, p] of u.pins) names.set(n, p.name);
  if (names.size !== part.pins.length || padOf.size !== part.pins.length) return undefined;

  const numbers = new Map<string, string>();
  for (const [number, name] of names) {
    const pad = padOf.get(name);
    if (pad === undefined || [...numbers.values()].includes(pad)) return undefined;
    numbers.set(number, pad);
  }
  if ([...numbers].every(([from, to]) => from === to)) return undefined;

  const name = part.spec.id;
  const local = sym.libId.slice(sym.libId.indexOf(":") + 1);
  const [head, , ...rest] = renumbered(sym.def, numbers);
  const body = rest.map((x) =>
    Array.isArray(x) && x[0] === "symbol"
      ? ["symbol", `${name}${(x[1] as string).slice(local.length)}`, ...x.slice(2)]
      : x,
  );
  const units = sym.units.map((u) => ({
    ...u,
    pins: new Map([...u.pins].map(([n, p]) => [numbers.get(n) ?? n, p])),
  }));
  const first = units[0] as SymbolUnit;
  return {
    ...sym,
    libId: `${LIB}:${name}`,
    def: ["symbol", `${LIB}:${name}`, ...body],
    units,
    generated: {
      name,
      def: [head as string, name, ...body],
      pins: first.pins,
      box: first.box,
      refPrefix: part.path.replace(/^.*\//, "").replace(/\d.*$/, ""),
    },
  };
}

/**
 * Why a KiCad symbol cannot stand in for the given parts, or undefined if it can: pin numbers
 * must match exactly; hidden pins must sit under a visible pin on the same net (KiCad's stacked
 * pins), and hidden power inputs are refused because KiCad connects those globally by name.
 */
export function incompatibility(sym: SchSymbol, parts: FlatPart[]): string | undefined {
  const all = new Map<string, UnitPin>();
  for (const u of sym.units) for (const [n, p] of u.pins) all.set(n, p);
  const first = parts[0];
  if (!first) return undefined;
  const want = new Set(first.pins.map((p) => p.number));
  const natural = (a: string, b: string) => a.localeCompare(b, "en", { numeric: true });
  const missing = [...want].filter((n) => !all.has(n)).sort(natural);
  const extra = [...all.keys()].filter((n) => !want.has(n)).sort(natural);
  if (missing.length + extra.length > 0) {
    return `pin numbers differ (${[
      missing.length > 0 ? `symbol lacks ${missing.join(" ")}` : "",
      extra.length > 0 ? `symbol has extra ${extra.join(" ")}` : "",
    ]
      .filter(Boolean)
      .join("; ")})`;
  }
  for (const u of sym.units) {
    for (const [n, p] of u.pins) {
      if (!p.hidden) continue;
      if (p.type === "power_in") return `pin ${n} is a hidden power input`;
      const under = [...u.pins].find(
        ([m, q]) => m !== n && !q.hidden && q.x === p.x && q.y === p.y,
      );
      if (!under) return `hidden pin ${n} is not stacked under a visible pin`;
      for (const part of parts) {
        const net = (num: string) => part.pins.find((q) => q.number === num)?.net;
        if (net(n) !== net(under[0])) {
          return `${part.path}: stacked pins ${under[0]} and ${n} are on different nets`;
        }
      }
    }
  }
  return undefined;
}

const normalize = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]/g, "");

/** `MCP6002-xSN` → /^MCP6002[A-Z0-9]SN$/ on normalized text: KiCad's lowercase x is a wildcard. */
function wildcardPattern(name: string): RegExp | undefined {
  if (!name.includes("x")) return undefined;
  let src = "";
  for (const ch of name) {
    if (ch === "x") src += "[A-Z0-9]";
    else if (/[A-Za-z0-9]/.test(ch)) src += ch.toUpperCase();
  }
  return new RegExp(`^${src}$`);
}

/**
 * Library symbols that plausibly are this part, best first: an exact name match on the id or
 * MPN, then a KiCad wildcard match (`MCP1700x-330xxTT`), then the longest name that is a prefix
 * of the MPN followed by a letter (`L7805` for `L7805CV`, but never `LM317` for `LM3171`), then
 * the shortest name the id is a prefix of. Pins vet the candidates afterwards.
 */
export function rankSymbolMatches(
  record: PartRecord,
  names: { lib: string; name: string }[],
  limit = 5,
): { lib: string; name: string }[] {
  const id = normalize(record.id);
  const keys = [...new Set([id, normalize(record.preferred_mpn ?? "")])].filter(Boolean);
  const scored: { lib: string; name: string; score: number }[] = [];
  for (const n of names) {
    const norm = normalize(n.name);
    if (norm.length < 3) continue;
    let score = 0;
    const pattern = wildcardPattern(n.name);
    for (const k of keys) {
      if (norm === k) score = Math.max(score, 3000);
      else if (pattern?.test(k)) score = Math.max(score, 2000 + norm.length);
      else if (norm.length >= 4 && k.startsWith(norm) && /[A-Z]/.test(k.charAt(norm.length))) {
        score = Math.max(score, 1000 + norm.length);
      }
    }
    // An id names the part without its ordering suffix: `MCP6002` for `MCP6002-xSN`.
    if (score === 0 && id.length >= 4 && norm.startsWith(id)) score = 500 - norm.length;
    if (score > 0) scored.push({ ...n, score });
  }
  return scored
    .sort((a, b) => b.score - a.score || a.lib.localeCompare(b.lib) || a.name.localeCompare(b.name))
    .slice(0, limit)
    .map(({ lib, name }) => ({ lib, name }));
}

/** Top-level symbol names in a .kicad_sym file, without parsing it. */
export function symbolNames(text: string): string[] {
  return [...text.matchAll(/^\t\(symbol "([^"]+)"\r?$/gm)].map((m) => m[1] as string);
}
