#!/usr/bin/env node
// Builds self-contained partstyle executables with Bun: the CLI, including `partstyle mcp`,
// with the grammar reference and the viewer embedded, so neither Node nor this checkout is
// needed to run it. Run after `pnpm build`.
//
//   node scripts/standalone.mjs [TARGET...]
//
// TARGET is a Bun target such as bun-linux-x64, bun-linux-arm64, bun-darwin-arm64,
// bun-darwin-x64 or bun-windows-x64 (default: this machine's). Executables go to
// packages/cli/standalone/out/partstyle-<os>-<arch>[.exe]. Set BUN to pick the bun binary.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = path.join(root, "packages", "cli", "standalone");
const viewerDist = path.join(root, "packages", "viewer", "dist");

// standalone.test.ts in packages/cli finds the native executable the same way.
const nativeTarget = () =>
  `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;

const outFile = (target) =>
  path.join(
    dir,
    "out",
    `partstyle-${target.replace(/^bun-/, "")}${target.includes("windows") ? ".exe" : ""}`,
  );

function viewerFiles(folder, prefix = "") {
  const files = {};
  for (const e of readdirSync(folder, { withFileTypes: true })) {
    const rel = `${prefix}${e.name}`;
    if (e.isDirectory()) Object.assign(files, viewerFiles(path.join(folder, e.name), `${rel}/`));
    else files[rel] = readFileSync(path.join(folder, e.name)).toString("base64");
  }
  return files;
}

function writeEntry() {
  for (const built of [
    path.join(viewerDist, "index.html"),
    path.join(dir, "..", "dist", "main.js"),
  ]) {
    if (!existsSync(built)) throw new Error(`${built} is missing: run pnpm build first`);
  }
  const grammar = readFileSync(path.join(root, "docs", "ckt-grammar.md"), "utf8");
  const entry = `// Generated by scripts/standalone.mjs; do not edit.
import { embedGrammarReference } from "@partstyle/engine/node";
import { embedViewer } from "@partstyle/server";

embedGrammarReference(${JSON.stringify(grammar)});
const viewer = ${JSON.stringify(viewerFiles(viewerDist))};
embedViewer(
  Object.fromEntries(Object.entries(viewer).map(([p, b]) => [p, Buffer.from(b, "base64")])),
);
await import("../dist/main.js");
`;
  mkdirSync(dir, { recursive: true });
  const file = path.join(dir, "entry.js");
  writeFileSync(file, entry, "utf8");
  return file;
}

const entry = writeEntry();
const targets = process.argv.slice(2);
for (const target of targets.length > 0 ? targets : [nativeTarget()]) {
  const out = outFile(target);
  execFileSync(
    process.env.BUN ?? "bun",
    [
      "build",
      entry,
      "--compile",
      "--minify",
      "--sourcemap",
      `--target=${target}`,
      "--outfile",
      out,
    ],
    { stdio: "inherit", cwd: dir },
  );
  console.log(`built ${path.relative(root, out)}`);
}
