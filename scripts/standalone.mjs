#!/usr/bin/env node
// Builds self-contained partstyle executables with Bun: the CLI, including `partstyle mcp`,
// with the grammar reference and the viewer embedded, so neither Node nor this checkout is
// needed to run it. Run after `pnpm build`.
//
//   node scripts/standalone.mjs [TARGET...]
//   node scripts/standalone.mjs --mcpb
//   node scripts/standalone.mjs --check-mcpb
//
// TARGET is a Bun target such as bun-linux-x64, bun-linux-arm64, bun-darwin-arm64,
// bun-darwin-x64 or bun-windows-x64 (default: this machine's). Executables go to
// packages/cli/standalone/out/partstyle-<os>-<arch>[.exe]. Set BUN to pick the bun binary.
// The builds report the version in packages/*/package.json (scripts/check-version.mjs keeps
// those in step), embedded since a standalone build has no package.json to read.
//
// --mcpb builds the Claude Desktop extension instead: the same entry bundled for Node (Claude
// Desktop runs it with its own Node.js) into out/mcpb/server/index.mjs, with the manifest from
// packages/cli/mcpb/manifest.json (that version, and the tools from the server itself),
// LICENSE and THIRD_PARTY_NOTICES.txt (also written to out/ for releases), packed as
// out/partstyle.mcpb. Building it also checks the bundle under this Node: MCP handshake and
// version, the grammar, and the viewer drawing a copy of examples/bench-sensor.
// --check-mcpb repeats only that check, e.g. under the oldest Node the manifest allows.
import { execFileSync, spawn } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = path.join(root, "packages", "cli", "standalone");
const viewerDist = path.join(root, "packages", "viewer", "dist");
const mcpbDir = path.join(dir, "out", "mcpb");
const mcpbServer = path.join(mcpbDir, "server", "index.mjs");
/** What the builds report, as `partstyle --version` from source does. */
const version = JSON.parse(
  readFileSync(path.join(root, "packages", "mcp", "package.json"), "utf8"),
).version;

// standalone.test.ts in packages/cli finds the native executable the same way.
const nativeTarget = () =>
  `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;

const outFile = (target) =>
  path.join(
    dir,
    "out",
    `partstyle-${target.replace(/^bun-/, "")}${target.includes("windows") ? ".exe" : ""}`,
  );

function viewerFiles(folder, prefix = "") {
  const files = {};
  for (const e of readdirSync(folder, { withFileTypes: true })) {
    const rel = `${prefix}${e.name}`;
    if (e.isDirectory()) Object.assign(files, viewerFiles(path.join(folder, e.name), `${rel}/`));
    else files[rel] = readFileSync(path.join(folder, e.name)).toString("base64");
  }
  return files;
}

function writeEntry() {
  for (const built of [
    path.join(viewerDist, "index.html"),
    path.join(dir, "..", "dist", "main.js"),
  ]) {
    if (!existsSync(built)) throw new Error(`${built} is missing: run pnpm build first`);
  }
  const grammar = readFileSync(path.join(root, "docs", "ckt-grammar.md"), "utf8");
  const partFormat = readFileSync(path.join(root, "docs", "part-records.md"), "utf8");
  const entry = `// Generated by scripts/standalone.mjs; do not edit.
import { embedReferences } from "@partstyle/engine/node";
import { embedVersion } from "@partstyle/mcp";
import { embedViewer } from "@partstyle/server";

embedVersion(${JSON.stringify(version)});
embedReferences(${JSON.stringify({ grammar, partFormat })});
const viewer = ${JSON.stringify(viewerFiles(viewerDist))};
embedViewer(
  Object.fromEntries(Object.entries(viewer).map(([p, b]) => [p, Buffer.from(b, "base64")])),
);
await import("../dist/main.js");
`;
  mkdirSync(dir, { recursive: true });
  const file = path.join(dir, "entry.js");
  writeFileSync(file, entry, "utf8");
  return file;
}

const bun = (args) => execFileSync(process.env.BUN ?? "bun", args, { stdio: "inherit", cwd: dir });

/**
 * Runs the bundled MCP server under this Node and exercises it the way Claude Desktop would;
 * returns its tools.
 */
async function checkServer(server) {
  const tmp = mkdtempSync(path.join(tmpdir(), "partstyle-mcpb-"));
  // The example's library path is ../../library.
  cpSync(path.join(root, "examples", "bench-sensor"), path.join(tmp, "examples", "bench-sensor"), {
    recursive: true,
    filter: (src) => !src.includes(".partstyle"),
  });
  cpSync(path.join(root, "library"), path.join(tmp, "library"), { recursive: true });
  const args = [server, "mcp", "--projects-dir", path.join(tmp, "examples"), "--viewer-port", "0"];
  const child = spawn(process.execPath, args, {
    env: { ...process.env, PARTSTYLE_STATE_DIR: path.join(tmp, "state") },
    stdio: ["pipe", "pipe", "inherit"],
  });
  const waiting = new Map();
  let buffer = "";
  child.stdout.setEncoding("utf8").on("data", (chunk) => {
    buffer += chunk;
    for (let i = buffer.indexOf("\n"); i >= 0; i = buffer.indexOf("\n")) {
      const line = buffer.slice(0, i).trim();
      buffer = buffer.slice(i + 1);
      if (line) {
        const message = JSON.parse(line);
        waiting.get(message.id)?.(message);
      }
    }
  });
  const send = (message) =>
    child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...message })}\n`);
  let next = 0;
  const request = (method, params = {}) =>
    new Promise((resolve, reject) => {
      const id = ++next;
      const timer = setTimeout(() => reject(new Error(`${method}: no answer`)), 60_000);
      waiting.set(id, (m) => {
        clearTimeout(timer);
        if (m.error) reject(new Error(`${method}: ${m.error.message}`));
        else resolve(m.result);
      });
      send({ id, method, params });
    });
  const call = async (name, args = {}) => {
    const r = await request("tools/call", { name, arguments: args });
    const text = r.content.map((c) => c.text).join("");
    if (r.isError) throw new Error(`${name}: ${text}`);
    return text;
  };
  try {
    const { serverInfo } = await request("initialize", {
      protocolVersion: "2025-06-18",
      capabilities: {},
      clientInfo: { name: "standalone.mjs", version: "0" },
    });
    if (serverInfo.version !== version) {
      throw new Error(`the server reports version ${serverInfo.version}, not ${version}`);
    }
    send({ method: "notifications/initialized" });
    const { tools } = await request("tools/list");
    if (!(await call("grammar")).startsWith("# .ckt grammar")) throw new Error("grammar missing");
    const opened = await call("open_project", { project: "bench-sensor" });
    const url = /^viewer: (\S+)\?/m.exec(opened)?.[1];
    if (!url) throw new Error(`no viewer:\n${opened}`);
    const model = await (await fetch(new URL("api/model", url))).json();
    const failed = model.issues.find((i) => i.code === "layout.failed");
    if (failed || model.sheets.length === 0) {
      throw new Error(`viewer cannot draw: ${failed?.message ?? "no sheets"}`);
    }
    console.log(`${server} works under Node ${process.version} (${tools.length} tools)`);
    return tools;
  } finally {
    child.stdin.end();
    child.kill();
    await new Promise((resolve) => child.once("exit", resolve));
    rmSync(tmp, { recursive: true, force: true });
  }
}

/** The package folder (…/node_modules/NAME or …/node_modules/@SCOPE/NAME) holding `file`. */
function packageRoot(file) {
  const parts = path.resolve(file).split(path.sep);
  const i = parts.lastIndexOf("node_modules");
  if (i < 0) return undefined;
  return parts.slice(0, i + (parts[i + 1]?.startsWith("@") ? 3 : 2)).join(path.sep);
}

/**
 * Third-party notices for what the bundle contains (from Bun's metafile), plus the Svelte
 * runtime compiled into the viewer: each package's name, version, license and license text.
 */
function writeNotices(metafile, outFiles) {
  const inputs = Object.keys(JSON.parse(readFileSync(metafile, "utf8")).inputs);
  const roots = new Set(inputs.map((f) => packageRoot(path.join(dir, f))).filter(Boolean));
  roots.add(path.join(root, "packages", "viewer", "node_modules", "svelte"));
  const entries = new Map();
  for (const r of roots) {
    const pkg = JSON.parse(readFileSync(path.join(r, "package.json"), "utf8"));
    const licenseFile = readdirSync(r).find((f) => /^(licen[cs]e|copying)([.\-_]|$)/i.test(f));
    const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
    const text = licenseFile
      ? readFileSync(path.join(r, licenseFile), "utf8").trim()
      : `Licensed under ${pkg.license}${author ? ` by ${author}` : ""}; the package includes no license text.${pkg.license === "Apache-2.0" ? " The Apache-2.0 text is in LICENSE." : ""}`;
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
    entries.set(`${pkg.name}@${pkg.version}`, {
      heading: `${pkg.name} ${pkg.version} (${pkg.license ?? "license in text below"})`,
      source: pkg.homepage ?? repo,
      text,
    });
  }
  const rule = "-".repeat(72);
  const body = [...entries.keys()].sort().map((k) => {
    const e = entries.get(k);
    return [rule, e.heading, ...(e.source ? [e.source] : []), "", e.text, ""].join("\n");
  });
  const notices = `Third-party software in Partstyle's release files

partstyle.mcpb and the standalone partstyle executables contain the packages below; the viewer
includes the Svelte runtime. Partstyle itself is licensed under Apache-2.0 (LICENSE), and the
seed part library under CC0-1.0 (library/LICENSE).

The standalone executables also contain the Bun runtime (https://bun.sh), which is MIT
licensed and includes JavaScriptCore and other components under their own licenses, some
LGPL; see LICENSE.md in https://github.com/oven-sh/bun.

${body.join("\n")}`;
  for (const f of outFiles) writeFileSync(f, notices, "utf8");
  return entries.size;
}

async function buildMcpb(entry) {
  rmSync(mcpbDir, { recursive: true, force: true });
  const metafile = path.join(dir, "out", "mcpb-meta.json");
  bun([
    "build",
    entry,
    "--target=node",
    "--minify",
    "--outfile",
    mcpbServer,
    `--metafile=${metafile}`,
  ]);
  const tools = await checkServer(mcpbServer);

  const n = writeNotices(metafile, [
    path.join(mcpbDir, "THIRD_PARTY_NOTICES.txt"),
    path.join(dir, "out", "THIRD_PARTY_NOTICES.txt"),
  ]);
  console.log(`third-party notices for ${n} packages`);
  cpSync(path.join(root, "LICENSE"), path.join(mcpbDir, "LICENSE"));

  const manifest = JSON.parse(
    readFileSync(path.join(root, "packages", "cli", "mcpb", "manifest.json"), "utf8"),
  );
  manifest.version = version;
  manifest.tools = tools.map((t) => ({ name: t.name, description: t.description }));
  writeFileSync(path.join(mcpbDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

  // The mcpb CLI (a root devDependency), run with this Node: its .bin shim is a .cmd on Windows.
  const pkg = path.join(root, "node_modules", "@anthropic-ai", "mcpb");
  const cli = path.join(pkg, JSON.parse(readFileSync(path.join(pkg, "package.json"), "utf8")).bin);
  const out = path.join(dir, "out", "partstyle.mcpb");
  execFileSync(process.execPath, [cli, "pack", mcpbDir, out], { stdio: "inherit" });
  console.log(`built ${path.relative(root, out)} (version ${manifest.version})`);
}

const args = process.argv.slice(2);
if (args.includes("--check-mcpb")) {
  if (!existsSync(mcpbServer)) throw new Error(`${mcpbServer} is missing: build it with --mcpb`);
  await checkServer(mcpbServer);
} else if (args.includes("--mcpb")) {
  await buildMcpb(writeEntry());
} else {
  const entry = writeEntry();
  for (const target of args.length > 0 ? args : [nativeTarget()]) {
    const out = outFile(target);
    bun([
      "build",
      entry,
      "--compile",
      "--minify",
      "--sourcemap",
      `--target=${target}`,
      "--outfile",
      out,
    ]);
    console.log(`built ${path.relative(root, out)}`);
  }
}
